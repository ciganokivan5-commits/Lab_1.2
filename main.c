#include <stdio.h>  // Бібліотека для введення/виведення (printf, scanf)
#include <stdlib.h> // Бібліотека для системних функцій (system)
#include <math.h>   // Бібліотека для математичних функцій (pow)

// Макрос: кількість рядків таблиці на одній сторінці перед паузою
#define PAGE_SIZE 8

// Обчислення значення математичної функції f(x) = x^4 - 5*x^3 - 0.25*x^2 + 2
double f(double x) {
    return fabs(pow(x - 200, 5) - pow(x - 100, 3) - 50 * x - 25);
}
int main() {
    int mode = 0;       // Режим обчислення кроку/кількості точок
    double X1, X2;      // Межі інтервалу [X1; X2]
    double delta;       // Крок табулювання
    unsigned int N;     // Кількість точок табулювання

    // === 1. ВИБІР РЕЖИМУ ТАБУЛЮВАННЯ ===
    printf("Режим (1 - N, 2 - delta): ");
    scanf("%d", &mode);
    // Перевірка коректності вибору режиму
    while (mode != 1 && mode != 2) {
        printf("Помилка (1 або 2): ");
        scanf("%d", &mode);
    }

    // === 2. ВВЕДЕННЯ ТА ВАЛІДАЦІЯ МЕЖ ІНТЕРВАЛУ ===
    printf("X1: ");
    scanf("%lf", &X1);
    printf("X2: ");
    scanf("%lf", &X2);

    // X2 обов'язково має бути більшим за X1
    while (X2 <= X1) {
        printf("Помилка (X2 має бути > X1): ");
        scanf("%lf", &X2);
    }

    // === 3. РОЗРАХУНОК КРОКУ ТА КІЛЬКОСТІ ТОЧОК ===
    if (mode == 1) {
        // Задається кількість точок N
        printf("N (>= 2): ");
        scanf("%u", &N);

        while (N < 2) {
            printf("Помилка (N >= 2): ");
            scanf("%u", &N);
        }
        // Обчислення кроку delta за кількості точок N
        delta = (X2 - X1) / (N - 1);
    }
    else {
        // Задається крок delta
        printf("delta (> 0): ");
        scanf("%lf", &delta);

        while (delta <= 0) {
            printf("Помилка (delta > 0): ");
            scanf("%lf", &delta);
        }
        // Обчислення кількості точок N за кроком delta
        N = (unsigned int)((X2 - X1) / delta) + 1;
    }

    // === 4. ВИВЕДЕННЯ ТАБЛИЦІ ЗНАЧЕНЬ (ТАБУЛЮВАННЯ) ===
    printf("\nX1=%.2f,  X2=%.2f,  delta=%.2f\n\n", X1, X2, delta);
    printf("***********************************\n");
    printf("*       N   *       X   *    F(X) *\n");
    printf("***********************************\n");

    int count = 0; // Лічильник рядків для сторінкового виводу

    for (unsigned int i = 1; i <= N; i++) {
        // Поточне значення x
        double x = X1 + (i - 1) * delta;

        // Корекція останньої точки для уникнення похибки округлення float/double
        if (x > X2) x = X2;

        double fx = f(x); // Значення функції в точці x

        // Виведення відформатованого рядка таблиці
        printf("+-----------+-----------+-----------+\n");
        printf("|%11u|%11.2f|%11.2f|\n", i, x, fx);

        count++; // Збільшуємо лічильник відображених рядків

        // Якщо виведено PAGE_SIZE (8) рядків і це не остання точка — робимо паузу
        if (count == PAGE_SIZE && i < N) {
            printf("+-----------+-----------+-----------+\n");
            printf("Press Any Key to Continue ...");
            system("pause"); // Запит на натискання клавіші (Windows)
            printf("\n");
            count = 0;      // Скидання лічильника для наступної сторінки
        }
    }
    printf("+-----------+-----------+-----------+\n");

    // === 5. ПОШУК ТА ВИВЕДЕННЯ ІНТЕРВАЛІВ ЗМІНИ ЗНАКА ===
    printf("\nІнтервали зміни знака:\n");

    int found = 0; // Прапорець: 1 — інтервал знайдено, 0 — ні

    for (unsigned int i = 1; i < N; i++) {
        double x1_curr = X1 + (i - 1) * delta;
        double x2_curr = X1 + i * delta;

        // Корекція правої межі поточного підінтервалу
        if (x2_curr > X2) x2_curr = X2;

        // Перевірка: якщо добуток f(x1) * f(x2) <= 0, то між x1 і x2 є нуль функції
        if (f(x1_curr) * f(x2_curr) <= 0) {
            printf("[%.2f; %.2f]\n", x1_curr, x2_curr);
            found = 1;
        }
    }

    // Якщо жодного інтервалу зміни знака не виявлено
    if (!found) {
        printf("Функція не змінює знак.\n");
    }

    return 0;
}

